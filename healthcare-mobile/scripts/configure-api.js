const fs = require('node:fs');
const path = require('node:path');

function validateUrl(value, name, httpsOnly = false) {
  let url;
  try { url = new URL(value); } catch { throw new Error(`${name} must be an absolute API base URL.`); }
  if (!['http:', 'https:'].includes(url.protocol) || (httpsOnly && url.protocol !== 'https:')
    || url.username || url.password || url.search || url.hash) {
    throw new Error(`${name} must use ${httpsOnly ? 'HTTPS' : 'HTTP or HTTPS'} without credentials, query parameters or fragments.`);
  }
  return url.toString().replace(/\/+$/, '');
}

function readApiConfig(env = process.env, production = false) {
  const sharedDevUrl = env.MOBILE_DEV_API_URL;
  const productionUrl = env.MOBILE_API_URL ? validateUrl(env.MOBILE_API_URL, 'MOBILE_API_URL', true) : undefined;
  if (production && !productionUrl) {
    throw new Error('MOBILE_API_URL is required for production. Set the real HTTPS API base URL, including its API path, before bundling.');
  }
  return {
    developmentUrls: {
      android: validateUrl(sharedDevUrl || 'http://10.0.2.2:3000/api/v1', 'MOBILE_DEV_API_URL'),
      ios: validateUrl(sharedDevUrl || 'http://localhost:3000/api/v1', 'MOBILE_DEV_API_URL'),
    },
    productionUrl,
  };
}

function generateApiConfig({ env = process.env, production = false, output = path.join(__dirname, '../src/api/host.ts') } = {}) {
  const config = readApiConfig(env, production);
  const content = '// AUTO-GENERATED by scripts/configure-api.js. Do not commit.\n'
    + `export const API_CONFIG = ${JSON.stringify({ ...config, productionUrl: config.productionUrl ?? null }, null, 2)} as const;\n`;
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== content) {
    fs.mkdirSync(path.dirname(output), { recursive: true });
    const temporary = `${output}.${process.pid}.tmp`;
    try { fs.writeFileSync(temporary, content, 'utf8'); fs.renameSync(temporary, output); }
    finally { if (fs.existsSync(temporary)) fs.unlinkSync(temporary); }
  }
  return config;
}

if (require.main === module) {
  try {
    generateApiConfig({ production: process.argv.includes('--production') });
    console.log('Mobile API configuration generated.');
  } catch (err) {
    console.error(err.message);
    process.exitCode = 1;
  }
}
module.exports = { readApiConfig, generateApiConfig };
